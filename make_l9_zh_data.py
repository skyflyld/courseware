def main():
    check_only = '--check' in sys.argv

    # --- 课文
    sents = collect()
    texts = {}
    for key, zh in (('t1', ZH_T1), ('t2', ZH_T2)):
        src = sents[key]
        if len(src) != len(zh):
            print('❌ %s 句数不匹配：源 %d / 译文 %d' % (key, len(src), len(zh)))
            for i, s in enumerate(src):
                mark = '✓' if i < len(zh) else '✗缺译文'
                print('   %s%02d %s' % (mark, i + 1, plain(s)))
            return 1
        texts[key] = {plain(s): t for s, t in zip(src, zh)}

    # --- 词场例句
    v9 = json.load(open(os.path.join(DIR, 'l9-vocab.json'), encoding='utf-8'))
    seen, idx = [], {}
    for g in v9['wortfelder']['groups']:
        for r in g['rows']:
            ex = r.get('ex', '')
            if ex and ex not in idx:
                idx[ex] = len(seen)
                seen.append(ex)
    if len(seen) != len(ZH_EX):
        print('❌ 例句条数不匹配：源 %d / 译文 %d' % (len(seen), len(ZH_EX)))
        for i, s in enumerate(seen):
            print('   %s%02d %s' % ('✓' if i < len(ZH_EX) else '✗缺译文', i + 1, s))
        return 1
    vocab = {ex: t for ex, t in zip(seen, ZH_EX)}

    fp = hashlib.sha1(('|'.join(seen) + '#' + '|'.join(plain(s) for s in sents['t1'] + sents['t2']))
                      .encode('utf-8')).hexdigest()[:12]
    print('✅ 课文 T1 %d 句 / T2 %d 句 · 词场例句 %d 条 · 指纹 %s'
          % (len(ZH_T1), len(ZH_T2), len(vocab), fp))
    if check_only:
        return 0

    with open(TEXT_OUT, 'w', encoding='utf-8') as f:
        json.dump({'_note': '键 = 课文德文原句（已去 %%…%% 标记，空白归一）；值 = 中文参考译文，非教材标准答案',
                   'fingerprint': fp, 't1': texts['t1'], 't2': texts['t2']},
                  f, ensure_ascii=False, indent=1)
    with open(VOCAB_OUT, 'w', encoding='utf-8') as f:
        json.dump({'_note': '键 = 教材例句德文原句；值 = 中文参考译文',
                   'fingerprint': fp, 'ex': vocab}, f, ensure_ascii=False, indent=1)
    print('写出 %s (%d B) / %s (%d B)'
          % (os.path.basename(TEXT_OUT), os.path.getsize(TEXT_OUT),
             os.path.basename(VOCAB_OUT), os.path.getsize(VOCAB_OUT)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
